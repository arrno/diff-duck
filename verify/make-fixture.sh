package users

import (
	"errors"
	"time"
)

// User is an account, now with a birth date.
type User struct {
	ID          string
	Name        string
	DateOfBirth time.Time `json:"dob"`
}

// Store persists users.
type Store interface {
	Save(u User) error
	Delete(id string) error
}

// Service manages users.
type Service struct {
	store Store
}

// Create stores a user after validating them.
func (s *Service) Create(u User) error {
	if u.Name == "" {
		return errors.New("name required")
	}
	if err := ValidateDOB(u.DateOfBirth); err != nil {
		return err
	}
	return s.store.Save(u)
}

// Untouched never changes.
func (s *Service) Untouched() int { return 1 }

// ValidateDOB rejects dates in the future.
func ValidateDOB(d time.Time) error {
	if d.After(time.Now()) {
		return errors.New("future date")
	}
	return nil
}

func addAndDouble(a, b int) int {
	sum := a + b
	return sum * 2
}

func formatted(a int) int {

	return a + 1
}

// commented gained a comment and nothing else.
func commented(a int) int {
	// Two is the right number.
	return a + 2
}

