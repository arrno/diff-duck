//go:embed wasm/c_sharp.wasm
var csharpWasm []byte

var csharpGrammar = Grammar{name: "c_sharp", wasm: csharpWasm}

// CSharp implements ports.SourceAnalyzer for C#.
//
// Structure: C# is a package language like Go, not a module language, so a file has no MODULE
// unit. A unit's package is PackageRef{Dir: the file's directory, Name: its namespace}, where
// the namespace is the enclosing block or file-scoped namespace ("Acme.Core" for nested
// namespace blocks), or the directory's name for the global namespace (empty at the repository
// root). A file declaring several namespaces gives each unit its own namespace; the file's
// FileAnalysis.Package is the first namespace it declares. Because units are keyed by package
// and name, the parts of a partial class in several files of one directory are the same type.
//
// Units, named within their namespace: classes (CLASS), structs (STRUCT), records and record
// structs (RECORD), interfaces (INTERFACE), enums (ENUM) with their members (ENUM_MEMBER), and
// delegates (TYPE). Inside a type: methods, constructors ("Repo.Repo(int)"; a static constructor
// is "Repo.static Repo()"), finalizers ("Repo.~Repo()"), and operators ("Repo.operator +(Repo,
// Repo)", "Repo.implicit operator int(Repo)") are METHODs; an interface method without a body is
// an INTERFACE_METHOD; properties, indexers ("Repo.this[int]"), and events with accessors are
// PROPERTYs; fields and field-like events are FIELDs, and const fields CONSTs, one unit per
// declared name. Nested types qualify their members: "Outer.Inner.Method()". An explicit
// interface implementation keeps its interface: "Repo.IRepo.Dispose()". Members declared inside
// #if blocks count. Top-level statements form one FUNCTION unit, "<top-level statements>", in
// the global namespace.
//
// Every method, constructor, finalizer, operator, and indexer is named with its parameter types,
// as C# identifies them: "Repo.Find(int)", "Repo.Find(string, ref int)", "Repo.Count()", with
// type parameters for generic methods, "Find<T>(T)". Modifiers that take part in overloading
// (ref, out, in, params, this) are kept; parameter names, tuple element names, attributes,
// default values, comments, and formatting are not. So overloads have unique names, a method
// never shares a name with a property, field, or nested type, and no name depends on its
// siblings: adding or removing an overload leaves the others alone. Changing a parameter's type
// changes the name; when the body is identical, the differ follows it like a rename, since
// BodyHash leaves the name and parameter types out. Nullable annotations are kept, since
// "int?" and "int" are different overloads, so annotating "string" as "string?" also changes the
// name. Types with the same name and different type parameters are told apart by them: "Box"
// and "Box<T>".
//
// An enum member without an explicit value gets its value from its position, so its hash
// includes that position and the last explicit value before it: inserting or reordering members
// changes those whose values changed. Hashes cover attributes and modifiers, ignore comments
// and formatting, and count every character inside string, verbatim, raw, interpolated, and
// character literals. /// comments before a declaration are its Doc. Every unit's Source is a
// slice of one copy of the file. A file whose qualified names would grow far beyond its own
// size, as only deliberately nested code can, is refused as too large.
//
// A file is a test file by path (*Test.cs, *Tests.cs, or a Tests, Test, *.Tests, or *.UnitTests
// directory) or when it uses a test attribute such as [Fact], [Test], or [TestMethod]. It is
// generated when its leading comments contain <auto-generated>, or by name (*.g.cs, *.g.i.cs,
// *.designer.cs, *.generated.cs). [GeneratedCode] attributes are not used, since the C#
// compiler itself does not treat them as marking a file generated.
type CSharp struct{ rt *Runtime }

// NewCSharp returns a C# analyzer running on rt.
func NewCSharp(rt *Runtime) *CSharp { return &CSharp{rt: rt} }

// Supports reports whether the path is a C# source file.
func (*CSharp) Supports(p string) bool { return strings.HasSuffix(p, ".cs") }

// csTopLevel names the unit holding a file's top-level statements.
const csTopLevel = "<top-level statements>"

// Analyze parses one C# file into units.
func (a *CSharp) Analyze(ctx context.Context, p string, src []byte) (domain.FileAnalysis, error) {
	tree, err := parseClean(ctx, a.rt, csharpGrammar, p, src)
	if err != nil {
		return domain.FileAnalysis{}, err
	}
	return extractCSharp(ctx, tree, p)
}

// extractCSharp extracts the units of a cleanly parsed C# file.
func extractCSharp(ctx context.Context, tree *Tree, p string) (domain.FileAnalysis, error) {
	root := tree.Root()
	e := &csExtractor{
		fileUnits: newFileUnits(ctx, tree, p, dirPackage(p), isCSharpTestPath(p) || csUsesTestAttributes(tree)),
	}
	e.scope(root, "", "", false, map[Node]bool{})
	return e.analysis(domain.FileAnalysis{
		Package:   e.pkgOf(e.firstNS),
		Generated: isCSharpGenerated(p, root),
	})
}

// csExtractor's fileUnits package is the global namespace's; each unit's is its namespace's.
type csExtractor struct {
	fileUnits
	firstNS string // the first namespace the file declares
}

// qualify names a declaration inside a type; a top-level type has its simple name.
func (e *csExtractor) qualify(scope, name string) string {
	if scope == "" {
		return name
	}
	return e.fileUnits.qualify(scope, name)
}

// pkgOf returns the package of a namespace; the global namespace is named after the directory.
func (e *csExtractor) pkgOf(ns string) domain.PackageRef {
	if ns == "" {
		return e.pkg
	}
	return domain.PackageRef{Dir: e.pkg.Dir, Name: ns, Hierarchical: e.pkg.Hierarchical}
}

func (e *csExtractor) unit(u domain.Unit, ns string, n Node) domain.Unit {
	u = e.finish(u)
	u.Package = e.pkgOf(ns)
	u.StartLine, u.EndLine = n.StartLine(), n.EndLine()
	u.Source = n.Text()
	return u
}

func (e *csExtractor) add(u domain.Unit, ns string, n Node) {
	e.units = append(e.units, e.unit(u, ns, n))
}

// csDecl is a declaration with the /// comments that precede it.
type csDecl struct {
	node Node
	doc  string
}

// csFlatten lists the declarations in a container, looking through #if blocks, with their doc
// comments. Comments are read in one pass, so a container with many members stays linear.
func csFlatten(container Node, out []csDecl) []csDecl {
	var doc []string
	for _, c := range container.Children() {
		if c.IsExtra() {
			if c.Type() == "comment" && strings.HasPrefix(c.Text(), "///") {
				doc = append(doc, c.Text())
			} else {
				doc = nil
			}
			continue
		}
		switch {
		case !c.IsNamed():
		case c.Type() == "preproc_if" || c.Type() == "preproc_elif" || c.Type() == "preproc_else":
			out = csFlatten(c, out)
		default:
			out = append(out, csDecl{node: c, doc: csCleanDoc(doc)})
		}
		doc = nil
	}
	return out
}

// scope extracts the declarations in a compilation unit, namespace body, or type body. ns is
// the namespace, and typeName the enclosing type's name, empty outside types. Declarations
// that became units are recorded in owned, so the enclosing type's hash leaves them out.
func (e *csExtractor) scope(container Node, ns, typeName string, inInterface bool, owned map[Node]bool) {
	decls := csFlatten(container, nil)
	names := csMemberNames(decls)
	var globals []Node
	for _, d := range decls {
		if e.stopped() {
			return
		}
		n := d.node
		switch n.Type() {
		case "file_scoped_namespace_declaration":
			ns = e.namespace(ns, n)
			e.noteNamespace(ns)
		case "namespace_declaration":
			inner := e.namespace(ns, n)
			e.noteNamespace(inner)
			e.scope(n.ChildByField("body"), inner, "", false, map[Node]bool{})
		case "global_statement":
			globals = append(globals, n)
		case "class_declaration", "struct_declaration", "record_declaration", "interface_declaration", "enum_declaration":
			e.typeDecl(d, ns, typeName, names[n])
			owned[n] = true
		case "delegate_declaration":
			e.add(domain.Unit{
				Kind:      domain.KindType,
				Name:      e.qualify(typeName, names[n]),
				Parent:    typeName,
				Signature: strings.TrimSuffix(n.Text(), ";"),
				Hash:      csHash(nil).hash(n),
				Doc:       d.doc,
			}, ns, n)
			owned[n] = true
		case "method_declaration", "constructor_declaration", "destructor_declaration",
			"operator_declaration", "conversion_operator_declaration":
			e.callable(d, ns, typeName, names[n], inInterface)
			owned[n] = true
		case "property_declaration", "indexer_declaration", "event_declaration":
			e.add(domain.Unit{
				Kind:      domain.KindProperty,
				Name:      e.qualify(typeName, names[n]),
				Parent:    typeName,
				Signature: csHeader(n),
				Hash:      csHash(nil).hash(n),
				Doc:       d.doc,
			}, ns, n)
			owned[n] = true
		case "field_declaration", "event_field_declaration":
			e.fields(d, ns, typeName)
			owned[n] = true
		}
	}
	if len(globals) > 0 {
		first, last := globals[0], globals[len(globals)-1]
		u := domain.Unit{
			Kind:      domain.KindFunction,
			Name:      csTopLevel,
			Signature: "top-level statements",
			Hash:      csHash(nil).hash(globals...),
		}
		u.StartLine, u.EndLine = first.StartLine(), last.EndLine()
		u.Source = first.TextUntil(last.EndByte())
		e.units = append(e.units, e.finish(u))
	}
}

func (e *csExtractor) noteNamespace(ns string) {
	if e.firstNS == "" {
		e.firstNS = ns
	}
}

// typeDecl extracts a class, struct, record, interface, or enum and its members.
func (e *csExtractor) typeDecl(d csDecl, ns, scope, name string) {
	n := d.node
	qualified := e.qualify(scope, name)
	slot := e.reserve()
	members := map[Node]bool{}
	body := n.ChildByField("body")
	kind := domain.KindClass
	switch n.Type() {
	case "struct_declaration":
		kind = domain.KindStruct
	case "record_declaration":
		kind = domain.KindRecord
	case "interface_declaration":
		kind = domain.KindInterface
	case "enum_declaration":
		kind = domain.KindEnum
	}
	if kind == domain.KindEnum {
		e.enumMembers(body, ns, qualified, members)
	} else if !body.IsNull() {
		e.scope(body, ns, qualified, kind == domain.KindInterface, members)
	}
	e.units[slot] = e.unit(domain.Unit{
		Kind:      kind,
		Name:      qualified,
		Parent:    scope,
		Signature: csHeader(n),
		// The type's own code: attributes, header, and anything that is not a member. A
		// member's change belongs to that member alone.
		Hash: csHash(members).hash(n),
		Doc:  d.doc,
	}, ns, n)
}

// enumMembers extracts an enum's members. A member without a value is one more than the member
// before it, so its hash includes how far it is from the last explicit value, and that value.
func (e *csExtractor) enumMembers(body Node, ns, enum string, owned map[Node]bool) {
	from, offset := "start", 0
	for _, d := range csFlatten(body, nil) {
		if e.stopped() {
			break
		}
		n := d.node
		if n.Type() != "enum_member_declaration" || e.stopped() {
			continue
		}
		u := domain.Unit{
			Kind:      domain.KindEnumMember,
			Name:      e.qualify(enum, n.ChildByField("name").Text()),
			Parent:    enum,
			Signature: n.Text(),
			Hash:      csHash(nil).hash(n),
			Doc:       d.doc,
		}
		if value := n.ChildByField("value"); value.IsNull() {
			u.Hash = hashStrings(u.Hash, from, fmt.Sprint(offset))
			u.ChangeNote = "Implicit value changed: its position after the last explicit value differs."
			offset++
		} else {
			from, offset = csHash(nil).hash(value), 1
		}
		e.add(u, ns, n)
		owned[n] = true
	}
}

// callable extracts a method, constructor, finalizer, or operator.
func (e *csExtractor) callable(d csDecl, ns, scope, name string, inInterface bool) {
	n := d.node
	body := n.ChildByField("body")
	kind := domain.KindMethod
	if inInterface && body.IsNull() {
		kind = domain.KindInterfaceMethod
	}
	u := domain.Unit{
		Kind:      kind,
		Name:      e.qualify(scope, name),
		Parent:    scope,
		Signature: csHeader(n),
		Hash:      csHash(nil).hash(n),
		Doc:       d.doc,
	}
	// Everything but what makes up the name, the name and the parameter types: attributes,
	// modifiers, type parameters, result, parameter names, and body. So renaming a method, or
	// changing a parameter's type, is followed when the body is identical. A body of one
	// statement is too common to prove that.
	if t := n.Type(); (t == "method_declaration" || t == "constructor_declaration") && body.Type() == "block" && len(body.NamedChildren()) >= 2 {
		params := n.ChildByField("parameters")
		without := map[Node]bool{n.ChildByField("name"): true, params: true}
		for _, c := range n.NamedChildren() {
			if c.Type() == "explicit_interface_specifier" {
				without[c] = true
			}
		}
		u.BodyHash = hashStrings("cs "+t, csParamNames(params), csHash(without).hash(n))
	}
	e.add(u, ns, n)
}

// fields extracts a field or field-like event declaration: one unit per declared name, sharing
// the declaration's range and code.
func (e *csExtractor) fields(d csDecl, ns, scope string) {
	n := d.node
	kind := domain.KindField
	for _, c := range n.NamedChildren() {
		if c.Type() == "modifier" && c.Text() == "const" {
			kind = domain.KindConst
		}
	}
	var decl Node
	for _, c := range n.NamedChildren() {
		if c.Type() == "variable_declaration" {
			decl = c
		}
	}
	code := csHash(nil).hash(n)
	// Sliced and compacted once and shared by every name: a copy per name would grow with the
	// square of the declaration's length.
	signature := compact(strings.TrimSuffix(n.Text(), ";"))
	for _, v := range decl.NamedChildren() {
		if v.Type() != "variable_declarator" || e.stopped() {
			continue
		}
		name := v.ChildByField("name").Text()
		e.add(domain.Unit{
			Kind:      kind,
			Name:      e.qualify(scope, name),
			Parent:    scope,
			Signature: signature,
			Hash:      hashStrings(name, code),
			Doc:       d.doc,
		}, ns, n)
	}
}

// csMemberNames returns each declaration's name within its scope. Methods, constructors,
// finalizers, operators, and indexers always carry their parameter types. Types carry their
// type parameters only when types of one name differ by them, so a generic type keeps its
// plain name until a same-named sibling appears.
func csMemberNames(decls []csDecl) map[Node]string {
	base := map[Node]string{}
	count := map[string]int{}
	for _, d := range decls {
		if name := csBaseName(d.node); name != "" {
			base[d.node] = name
			if csIsType(d.node) {
				count[name]++
			}
		}
	}
	names := make(map[Node]string, len(base))
	for n, name := range base {
		if csIsCallable(n) || count[name] > 1 {
			name += csOverloadSuffix(n)
		}
		names[n] = name
	}
	return names
}

// csIsType reports whether a declaration declares a type.
func csIsType(n Node) bool {
	switch n.Type() {
	case "class_declaration", "struct_declaration", "record_declaration", "interface_declaration",
		"enum_declaration", "delegate_declaration":
		return true
	}
	return false
}

// csIsCallable reports whether a declaration is named with its parameters.
func csIsCallable(n Node) bool {
	switch n.Type() {
	case "method_declaration", "constructor_declaration", "destructor_declaration",
		"operator_declaration", "conversion_operator_declaration", "indexer_declaration":
		return true
	}
	return false
}

// csBaseName returns a declaration's name before overloads are told apart, or empty for
// declarations that are not named units here.
func csBaseName(n Node) string {
	explicit := ""
	for _, c := range n.NamedChildren() {
		if c.Type() == "explicit_interface_specifier" {
			explicit = csTokens(c)
		}
	}
	switch n.Type() {
	case "class_declaration", "struct_declaration", "record_declaration", "interface_declaration",
		"enum_declaration", "delegate_declaration", "method_declaration", "property_declaration",
		"event_declaration":
		return explicit + n.ChildByField("name").Text()
	case "constructor_declaration":
		name := n.ChildByField("name").Text()
		for _, c := range n.NamedChildren() {
			if c.Type() == "modifier" && c.Text() == "static" {
				return "static " + name
			}
		}
		return name
	case "destructor_declaration":
		return "~" + n.ChildByField("name").Text()
	case "indexer_declaration":
		return explicit + "this"
	case "operator_declaration", "conversion_operator_declaration":
		// The tokens from the operator keyword, or from implicit/explicit, up to the
		// parameters: "operator +", "operator checked -", "implicit operator int".
		var parts []string
		started := false
		for _, c := range n.Children() {
			if c.IsExtra() {
				continue
			}
			if c.Field() == "parameters" {
				break
			}
			switch c.Type() {
			case "operator", "implicit", "explicit":
				started = true
			}
			if started {
				parts = append(parts, csTokens(c))
			}
		}
		return explicit + strings.Join(parts, " ")
	}
	return ""
}

// csOverloadSuffix tells overloads apart by their type parameters and parameter types.
func csOverloadSuffix(n Node) string {
	var b strings.Builder
	params := n.ChildByField("parameters")
	for _, c := range n.NamedChildren() {
		if c.Type() == "type_parameter_list" {
			b.WriteString(csTokens(c))
		}
	}
	if csIsType(n) {
		return b.String()
	}
	open, closing := "(", ")"
	if params.Type() == "bracketed_parameter_list" {
		open, closing = "[", "]"
	}
	// A params parameter is not wrapped in a parameter node: its keyword, type, and name are
	// children of the list, so the list is read as comma-separated runs.
	var types, parts []string
	for _, c := range params.Children() {
		switch {
		case c.IsExtra() || c.Type() == "(" || c.Type() == ")" || c.Type() == "[" || c.Type() == "]":
		case c.Type() == ",":
			types = append(types, strings.Join(parts, " "))
			parts = nil
		default:
			parts = append(parts, csParameterType(c)...)
		}
	}
	if len(parts) > 0 {
		types = append(types, strings.Join(parts, " "))
	}
	b.WriteString(open + strings.Join(types, ", ") + closing)
	return b.String()
}

// csParameterType returns what identifies a parameter or a piece of one in an overload: its
// modifiers and keywords, such as ref or params, and its type, but not its name, attributes,
// or default value.
func csParameterType(n Node) []string {
	switch {
	case n.Type() == "parameter":
		var parts []string
		for _, c := range n.Children() {
			parts = append(parts, csParameterType(c)...)
		}
		return parts
	case n.Field() == "type":
		return []string{csTokens(n)}
	case n.Type() == "modifier":
		return []string{n.Text()}
	case !n.IsNamed() && !n.IsExtra() && n.Type() != "=" && n.Type() != ",":
		return []string{n.Text()} // keywords such as params, this, scoped, __arglist
	}
	return nil
}

// csTokens returns a node's tokens, spaced the same however the source was formatted:
// "Dictionary<string, List<int>>", and tuples without element names, "(int, string)".
func csTokens(n Node) string {
	var b strings.Builder
	var walk func(Node)
	walk = func(n Node) {
		if n.IsExtra() {
			return
		}
		kids := n.Children()
		if len(kids) > 0 {
			for _, c := range kids {
				// A tuple element's name is not part of its type's identity.
				if n.Type() == "tuple_element" && c.Field() == "name" {
					continue
				}
				walk(c)
			}
			return
		}
		text := n.Text()
		if text == "" {
			return
		}
		if b.Len() > 0 {
			prev := b.String()[b.Len()-1]
			if csWordByte(prev) && csWordByte(text[0]) || prev == ',' {
				b.WriteByte(' ')
			}
		}
		b.WriteString(text)
	}
	walk(n)
	return b.String()
}

func csWordByte(c byte) bool {
	return c == '_' || c == '@' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= 0x80
}

// csParamNames lists a parameter list's names, which BodyHash keeps while the types go to the
// unit's name.
func csParamNames(params Node) string {
	var names []string
	for _, c := range params.Children() {
		switch {
		case c.Type() == "parameter":
			names = append(names, c.ChildByField("name").Text())
		case c.Field() == "name":
			names = append(names, c.Text()) // a params parameter's name sits in the list
		}
	}
	return strings.Join(names, ",")
}

// namespace returns the namespace a declaration opens inside an outer one. Nested names repeat
// their outer ones, so they are charged to the file's name budget like any qualified name.
func (e *csExtractor) namespace(outer string, n Node) string {
	return e.qualify(outer, csTokens(n.ChildByField("name")))
}

// csHeader returns a declaration's text up to its body: attributes, modifiers, name, type and
// value parameters, base types, and constraints. A property keeps an accessor list without
// bodies, such as "{ get; private set; }".
func csHeader(n Node) string {
	end := n.EndByte()
	for _, c := range n.Children() {
		if csStartsBody(c) {
			end = c.StartByte()
			break
		}
	}
	return strings.TrimSuffix(strings.TrimSpace(n.TextUntil(end)), ";")
}

func csStartsBody(c Node) bool {
	switch c.Type() {
	case "declaration_list", "enum_member_declaration_list", "block", "arrow_expression_clause":
		return true
	case "accessor_list":
		for _, a := range c.NamedChildren() {
			if !a.ChildByField("body").IsNull() {
				return true
			}
		}
	}
	return false
}

// csHash fingerprints C# syntax. Nodes in owned are left out, so a type hashes only its own
// code. Differences a formatter makes without changing meaning do not count: redundant
// parentheses and trailing commas.
func csHash(owned map[Node]bool) fingerprint {
	return fingerprint{
		skip: func(n Node) bool { return owned[n] },
		// The tree already encodes precedence, so parentheses that only group are formatting.
		transparent: func(n Node) bool { return n.Type() == "parenthesized_expression" },
		// Inside a literal every character counts, including spaces. Some of a literal's text
		// lives in hidden tokens, such as an interpolation's format string, so whole literals
		// and string pieces are counted by their exact text.
		opaque: func(n Node) bool {
			switch n.Type() {
			case "string_literal", "verbatim_string_literal", "raw_string_literal", "character_literal",
				"string_content", "interpolation_format_clause", "interpolation_start", "interpolation_quote":
				return true
			}
			return false
		},
		token: func(n Node) (string, bool) {
			if n.Type() == "," {
				// Commas between enum members belong to the members, which are units of their
				// own; a trailing comma is formatting.
				if n.Parent().Type() == "enum_member_declaration_list" || n.NextSibling().Type() == "}" {
					return "", false
				}
			}
			return n.Text(), true
		},
	}
}

// csCleanDoc turns /// comment lines into text, dropping the <summary> wrapper.
func csCleanDoc(lines []string) string {
	var out []string
	for _, l := range lines {
		l = strings.TrimPrefix(strings.TrimSpace(l), "///")
		l = strings.TrimPrefix(l, " ")
		l = strings.ReplaceAll(strings.ReplaceAll(l, "<summary>", ""), "</summary>", "")
		out = append(out, strings.TrimRight(l, " \t\r"))
	}
	return strings.TrimSpace(strings.Join(out, "\n"))
}

// isCSharpTestPath reports whether a path follows .NET test project conventions.
func isCSharpTestPath(p string) bool {
	base := path.Base(p)
	if strings.HasSuffix(base, "Tests.cs") || strings.HasSuffix(base, "Test.cs") {
		return true
	}
	for _, dir := range strings.Split(path.Dir(p), "/") {
		switch {
		case dir == "Tests" || dir == "Test" || dir == "tests" || dir == "test":
			return true
		case strings.Contains(dir, ".") && (strings.HasSuffix(dir, "Tests") || strings.HasSuffix(dir, ".Test")):
			return true
		}
	}
	return false
}

// csTestAttributes are the attributes xUnit, NUnit, and MSTest use to mark tests.
var csTestAttributes = map[string]bool{
	"Fact": true, "Theory": true, "Test": true, "TestCase": true, "TestCaseSource": true,
	"TestFixture": true, "TestMethod": true, "DataTestMethod": true, "TestClass": true,
}

// isCSharpTestAttribute reports whether an attribute marks a test, such as [Fact] or
// [NUnit.Framework.TestAttribute].
func isCSharpTestAttribute(attr Node) bool {
	name := csTokens(attr.ChildByField("name"))
	if i := strings.LastIndexAny(name, ".:"); i >= 0 {
		name = name[i+1:]
	}
	return csTestAttributes[strings.TrimSuffix(name, "Attribute")]
}

// csUsesTestAttributes reports whether any declaration in the tree carries a test attribute.
func csUsesTestAttributes(tree *Tree) bool {
	return tree.Any(func(n Node) bool { return n.Type() == "attribute" && isCSharpTestAttribute(n) })
}

// isCSharpGenerated reports whether a file is generated, by the conventions the C# compiler
// uses: a generated file name, or an <auto-generated> marker in the file's leading comments.
func isCSharpGenerated(p string, root Node) bool {
	base := strings.ToLower(path.Base(p))
	for _, suffix := range []string{".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"} {
		if strings.HasSuffix(base, suffix) {
			return true
		}
	}
	if strings.HasPrefix(base, "temporarygeneratedfile_") {
		return true
	}
	header := leadingComments(root)
	return strings.Contains(header, "<auto-generated") || strings.Contains(header, "<autogenerated")
}
